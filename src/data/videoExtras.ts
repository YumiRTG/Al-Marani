export function addVideoLibrary(module: LearningModule): LearningModule {
  const videos = videoLibraries[module.id];
  if (!videos?.length || module.topics.some(topic => topic.id === 'video-mediathek')) return module;

  return {
    ...module,
    topics: [
      ...module.topics,
      {
        id: 'video-mediathek',
        title: '🎬 Video-Mediathek – anschauen, stoppen, selbst erklären',
        content: [
          {
            type: 'info',
            title: 'So nutzt du die Videos richtig',
            text: 'Nicht nur laufen lassen: Lies vor jedem Video die Beobachtungsaufgabe, stoppe danach und erkläre den Inhalt ohne nachzulesen. Wenn das nicht klappt, sieh die entscheidende Stelle noch einmal an.',
          },
          ...videos,
          {
            type: 'warning',
            title: 'Mini-Lerncheck nach jedem Video',
            text: 'Kannst du in 30 Sekunden erklären: 1. Worum ging es? 2. Welche zwei Fachbegriffe waren wichtig? 3. Was könnte dazu in einer MFA-Prüfung gefragt werden?',
          },
        ],
      },
    ],
  };
}
